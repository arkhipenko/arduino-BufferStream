#include <limits.h>

#include "ReadBufferStream.h"

////////////////////////////////////////////////////////////////////////////////////////////////////
ReadBufferStream::ReadBufferStream(const void *buff, size_t len) : BaseBufferStream(const_cast<void *>(buff), len) {
	setTimeout(0);
}

////////////////////////////////////////////////////////////////////////////////////////////////////
int ReadBufferStream::available() {
	return len > (size_t) INT_MAX ? INT_MAX : (int) len;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
int ReadBufferStream::read() {
	if (len == 0) {
		return -1;
	}
	--len;
	return *buff++;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
int ReadBufferStream::peek() {
	if (len == 0) {
		return -1;
	}
	return *buff;
}
